-- Tamilflix movie request feature: run this in Supabase SQL Editor once.
-- Replace admin@example.com with the email of the account you use to sign in as Tamilflix admin.
create table if not exists public.movie_requests (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  language text not null default 'Any language',
  category text not null default 'Movies',
  notes text not null default '' check (char_length(notes) <= 500),
  status text not null default 'Pending' check (status in ('Pending','Approved','Declined','Added')),
  user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
alter table public.movie_requests enable row level security;
-- Visitors may submit a request, but cannot read everyone else's requests.
drop policy if exists "Anyone can submit movie requests" on public.movie_requests;
create policy "Anyone can submit movie requests" on public.movie_requests for insert to anon, authenticated with check (true);
-- Only the configured admin email can view/update/delete requests.
drop policy if exists "Admin can view movie requests" on public.movie_requests;
create policy "Admin can view movie requests" on public.movie_requests for select to authenticated using ((auth.jwt() ->> 'email') = 'admin@example.com');
drop policy if exists "Admin can update movie requests" on public.movie_requests;
create policy "Admin can update movie requests" on public.movie_requests for update to authenticated using ((auth.jwt() ->> 'email') = 'admin@example.com') with check ((auth.jwt() ->> 'email') = 'admin@example.com');
drop policy if exists "Admin can delete movie requests" on public.movie_requests;
create policy "Admin can delete movie requests" on public.movie_requests for delete to authenticated using ((auth.jwt() ->> 'email') = 'admin@example.com');
